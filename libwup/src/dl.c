/* dl: shared libraries at run time (include/dlfcn.h): a loader for the ARM ELF shared objects wupbuild builds
 * (app.cfg shared = yes: position independent, bound at once, a SysV hash table).
 *
 * dlopen reads the library's loadable segments into one block of the heap, as they lie in its address space, clears
 * what is not in the file (.bss), and applies its relocations: R_ARM_RELATIVE (the block's address added),
 * R_ARM_ABS32, R_ARM_GLOB_DAT, R_ARM_JUMP_SLOT (a symbol's address: the library's own, or the app's from its export
 * table, wupbuild's dl = yes). The new code is cleaned out of the data cache and the instruction cache dropped; then
 * its constructors run (DT_INIT, DT_INIT_ARRAY). dlclose runs its destructors (those registered with __cxa_atexit,
 * DT_FINI_ARRAY, DT_FINI) and frees the block. Every symbol is bound at dlopen: no lazy binding, no PLT resolver. */
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "dlfcn.h"
#include "armcpu.h"

/* the app's exports, generated by wupbuild (dl = yes), sorted by name */
typedef struct { const char *name; void *addr; } wup_dl_export_t;
extern const wup_dl_export_t wup__dl_exports[];
extern const unsigned wup__dl_nexports;

/* ---- ELF32, as much as this needs */
typedef struct { uint8_t ident[16]; uint16_t type, machine; uint32_t version, entry, phoff, shoff, flags;
                 uint16_t ehsize, phentsize, phnum, shentsize, shnum, shstrndx; } ehdr_t;
typedef struct { uint32_t type, offset, vaddr, paddr, filesz, memsz, flags, align; } phdr_t;
typedef struct { uint32_t name, value, size; uint8_t info, other; uint16_t shndx; } sym_t;
typedef struct { uint32_t offset, info; } rel_t;
enum { PT_LOAD = 1, PT_DYNAMIC = 2, ET_DYN = 3, EM_ARM = 40 };
enum { DT_NULL = 0, DT_HASH = 4, DT_STRTAB = 5, DT_SYMTAB = 6, DT_RELA = 7, DT_INIT = 12, DT_FINI = 13,
       DT_REL = 17, DT_RELSZ = 18, DT_PLTRELSZ = 2, DT_JMPREL = 23, DT_INIT_ARRAY = 25, DT_FINI_ARRAY = 26,
       DT_INIT_ARRAYSZ = 27, DT_FINI_ARRAYSZ = 28 };
enum { R_ARM_NONE = 0, R_ARM_ABS32 = 2, R_ARM_GLOB_DAT = 21, R_ARM_JUMP_SLOT = 22, R_ARM_RELATIVE = 23 };
enum { STB_WEAK = 2, SHN_UNDEF = 0 };

typedef struct atexit_s { void (*fn)(void *); void *arg; struct atexit_s *next; } atexit_t;
typedef struct lib_s {
    struct lib_s *next;
    uint8_t *base; uint32_t span;
    const sym_t *syms; const char *strs; uint32_t nsyms;
    uint32_t fini, fini_array, fini_arraysz;
    atexit_t *atexit;                                  /* (its C++ static objects' destructors) */
    int refs;
    char path[96];
} lib_t;
static lib_t *libs;
static char err[160];
static void fail(const char *what, const char *path) { snprintf(err, sizeof err, "%s: %s", path ? path : "", what); }

char *dlerror(void) { if (!err[0]) return NULL; static char out[160]; strcpy(out, err); err[0] = 0; return out; }

static void *app_symbol(const char *name) {           /* (the export table: binary search) */
    unsigned lo = 0, hi = wup__dl_nexports;
    while (lo < hi) {
        unsigned mid = (lo + hi) / 2;
        int c = strcmp(name, wup__dl_exports[mid].name);
        if (!c) return wup__dl_exports[mid].addr;
        if (c < 0) hi = mid; else lo = mid + 1;
    }
    return NULL;
}
static void *lib_symbol(const lib_t *l, const char *name) {   /* (its own definitions) */
    for (uint32_t i = 1; i < l->nsyms; i++) {
        const sym_t *s = &l->syms[i];
        if (s->shndx != SHN_UNDEF && (s->info >> 4) != 0 && !strcmp(l->strs + s->name, name)) return l->base + s->value;
    }
    return NULL;
}
/* a symbol a relocation names: the library's own, else the app's; a weak one may be missing (0) */
static int resolve(const lib_t *l, uint32_t index, uint32_t *out) {
    const sym_t *s = &l->syms[index];
    if (!index) { *out = 0; return 0; }
    if (s->shndx != SHN_UNDEF) { *out = (uint32_t)(l->base + s->value); return 0; }
    void *a = app_symbol(l->strs + s->name);
    if (a || (s->info >> 4) == STB_WEAK) { *out = (uint32_t)a; return 0; }
    snprintf(err, sizeof err, "%s: undefined symbol %s", l->path, l->strs + s->name);
    return -1;
}
static int relocate(lib_t *l, const rel_t *r, uint32_t bytes) {
    for (uint32_t i = 0; i < bytes / sizeof *r; i++) {
        uint32_t *p = (uint32_t *)(l->base + r[i].offset), type = r[i].info & 0xff, sym = r[i].info >> 8, v;
        if (r[i].offset + 4 > l->span) { fail("relocation outside the library", l->path); return -1; }
        switch (type) {
            case R_ARM_NONE: break;
            case R_ARM_RELATIVE: *p += (uint32_t)l->base; break;
            case R_ARM_ABS32: if (resolve(l, sym, &v)) return -1; *p += v; break;
            case R_ARM_GLOB_DAT: case R_ARM_JUMP_SLOT: if (resolve(l, sym, &v)) return -1; *p = v; break;
            default: snprintf(err, sizeof err, "%s: relocation type %u not supported", l->path, (unsigned)type); return -1;
        }
    }
    return 0;
}

void *dlopen(const char *path, int mode) {
    (void)mode;
    if (!path) { fail("no path", NULL); return NULL; }
    for (lib_t *l = libs; l; l = l->next) if (!strcmp(l->path, path)) { l->refs++; return l; }   /* (once) */
    FILE *f = fopen(path, "rb");
    if (!f) { fail("cannot open", path); return NULL; }
    ehdr_t eh; phdr_t ph[16];
    lib_t *l = NULL;
    if (fread(&eh, sizeof eh, 1, f) != 1 || memcmp(eh.ident, "\177ELF", 4) || eh.ident[4] != 1 || eh.type != ET_DYN
        || eh.machine != EM_ARM || eh.phnum > 16 || eh.phentsize != sizeof(phdr_t)) { fail("not an ARM shared library", path); goto bad; }
    if (fseek(f, (long)eh.phoff, SEEK_SET) || fread(ph, sizeof *ph, eh.phnum, f) != eh.phnum) { fail("damaged", path); goto bad; }
    uint32_t span = 0, dyn = 0, align = 64;
    for (int i = 0; i < eh.phnum; i++) {
        if (ph[i].type == PT_LOAD) {
            if (ph[i].vaddr + ph[i].memsz > span) span = ph[i].vaddr + ph[i].memsz;
            if (ph[i].align > align) align = ph[i].align;
        }
        if (ph[i].type == PT_DYNAMIC) dyn = ph[i].vaddr;
    }
    if (!span || !dyn) { fail("no segments", path); goto bad; }
    if (align > 4096) align = 4096;
    l = (lib_t *)calloc(1, sizeof *l);
    if (!l || !(l->base = (uint8_t *)aligned_alloc(align, (span + align - 1) & ~(align - 1)))) { fail("not enough memory", path); goto bad; }
    l->span = span; l->refs = 1;
    strncpy(l->path, path, sizeof l->path - 1);
    memset(l->base, 0, span);
    for (int i = 0; i < eh.phnum; i++)                 /* the segments, where they lie (.bss: the zeros above) */
        if (ph[i].type == PT_LOAD && ph[i].filesz
            && (fseek(f, (long)ph[i].offset, SEEK_SET) || fread(l->base + ph[i].vaddr, 1, ph[i].filesz, f) != ph[i].filesz)) { fail("damaged", path); goto bad; }
    fclose(f); f = NULL;

    /* the dynamic section: the symbols, the relocations, the constructors */
    uint32_t rel = 0, relsz = 0, jmprel = 0, jmprelsz = 0, init = 0, init_array = 0, init_arraysz = 0, hash = 0;
    for (const uint32_t *d = (const uint32_t *)(l->base + dyn); d[0] != DT_NULL; d += 2) {
        switch (d[0]) {
            case DT_HASH: hash = d[1]; break;
            case DT_SYMTAB: l->syms = (const sym_t *)(l->base + d[1]); break;
            case DT_STRTAB: l->strs = (const char *)(l->base + d[1]); break;
            case DT_REL: rel = d[1]; break;
            case DT_RELSZ: relsz = d[1]; break;
            case DT_JMPREL: jmprel = d[1]; break;
            case DT_PLTRELSZ: jmprelsz = d[1]; break;
            case DT_RELA: fail("RELA relocations: not built by wupbuild", path); goto bad;
            case DT_INIT: init = d[1]; break;
            case DT_FINI: l->fini = d[1]; break;
            case DT_INIT_ARRAY: init_array = d[1]; break;
            case DT_INIT_ARRAYSZ: init_arraysz = d[1]; break;
            case DT_FINI_ARRAY: l->fini_array = d[1]; break;
            case DT_FINI_ARRAYSZ: l->fini_arraysz = d[1]; break;
        }
    }
    if (!l->syms || !l->strs || !hash) { fail("no symbol table (built with --hash-style=sysv?)", path); goto bad; }
    l->nsyms = ((const uint32_t *)(l->base + hash))[1];   /* (the hash table's chain count: one per symbol) */
    if ((rel && relocate(l, (const rel_t *)(l->base + rel), relsz)) || (jmprel && relocate(l, (const rel_t *)(l->base + jmprel), jmprelsz))) goto bad;
    sync_code((uint32_t)l->base, span);                /* (the code, written as data: to RAM, and the I-cache dropped) */
    l->next = libs; libs = l;
    if (init) ((void (*)(void))(l->base + init))();
    for (uint32_t i = 0; i < init_arraysz / 4; i++) ((void (**)(void))(l->base + init_array))[i]();
    return l;
bad:
    if (f) fclose(f);
    if (l) { free(l->base); free(l); }
    return NULL;
}

void *dlsym(void *handle, const char *name) {
    void *a = handle == RTLD_DEFAULT ? app_symbol(name) : lib_symbol((const lib_t *)handle, name);
    if (!a) snprintf(err, sizeof err, "%s: no symbol %s", handle ? ((const lib_t *)handle)->path : "app", name);
    return a;
}

int dlclose(void *handle) {
    lib_t *l = (lib_t *)handle, **pp;
    if (!l) return -1;
    if (--l->refs > 0) return 0;
    for (atexit_t *a = l->atexit, *n; a; a = n) { n = a->next; a->fn(a->arg); free(a); }   /* (last registered first) */
    for (uint32_t i = l->fini_arraysz / 4; i-- > 0; ) ((void (**)(void))(l->base + l->fini_array))[i]();
    if (l->fini) ((void (*)(void))(l->base + l->fini))();
    for (pp = &libs; *pp; pp = &(*pp)->next) if (*pp == l) { *pp = l->next; break; }
    free(l->base); free(l);
    return 0;
}

/* C++ static objects register their destructors here (with their library's __dso_handle): run at its dlclose. The
   app's own (no library's handle) would run at its exit, which ends everything anyway: not kept. */
int __cxa_atexit(void (*fn)(void *), void *arg, void *dso) {
    for (lib_t *l = libs; l; l = l->next)
        if ((uint8_t *)dso >= l->base && (uint8_t *)dso < l->base + l->span) {
            atexit_t *a = (atexit_t *)malloc(sizeof *a);
            if (!a) return -1;
            a->fn = fn; a->arg = arg; a->next = l->atexit; l->atexit = a;
            return 0;
        }
    return 0;
}

/* which library an address is in (a crash report's return address): its path and the offset in it, or NULL */
const char *wup_dl_where(const void *addr, unsigned int *offset) {
    for (lib_t *l = libs; l; l = l->next)
        if ((const uint8_t *)addr >= l->base && (const uint8_t *)addr < l->base + l->span) {
            if (offset) *offset = (unsigned int)((const uint8_t *)addr - l->base);
            return l->path;
        }
    return NULL;
}
